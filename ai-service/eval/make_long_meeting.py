"""Builds eval/meetings/long.json.

About 4,500 words of neutral discussion with four tasks and one decision
planted at the start and at the quarter points. It tests whether the model's
context window is large enough and whether it still finds items in a long
recording. The random seed is fixed, so the output is always the same.

Run it from the ai-service folder:  python eval/make_long_meeting.py
"""

import json
import random
from pathlib import Path


OUTPUT_FILE = Path(__file__).parent / "meetings" / "long.json"

TOTAL_SENTENCES = 230


# ============================================================
# NEUTRAL FILLER SENTENCES (no commitments, no decisions)
# ============================================================

TOPICS = [
    "the checkout conversion rate", "the mobile app crash rate", "page load times",
    "the support ticket backlog", "the new search feature", "the onboarding funnel",
    "cloud hosting costs", "the recommendation engine", "our test coverage",
    "the nightly build", "customer churn", "the analytics pipeline",
    "the notification service", "the billing reports", "the API response times",
    "the design system", "the data warehouse", "the email campaigns",
    "the partner integrations", "the security audit results",
]

PERIODS = [
    "last quarter", "last month", "the past two weeks",
    "the same period last year", "this week", "over the summer",
]

TRENDS = [
    "went up a little", "dropped slightly", "stayed flat", "was noisy",
    "looked better than expected", "looked worse than we hoped",
    "fluctuated quite a bit", "improved steadily",
]

REACTIONS = [
    "which was interesting", "which surprised a few people",
    "and nobody was sure why", "which matches what customers told us",
    "though the sample is small", "which is about what we expected",
]

FEELS = [
    "felt slower", "felt faster", "felt about the same",
    "felt less reliable", "felt more stable",
]

OPENERS = ["So, ", "Okay, ", "Right, ", "Yeah, ", "Um, ", "You know, ", "Anyway, ", "", "", ""]


# ============================================================
# THE PLANTED ITEMS (sentence number -> sentence)
# ============================================================

PLANTED = {
    2: "Dana will send the budget proposal to finance by Monday.",
    57: "We decided to switch the hosting provider to Hetzner.",
    115: "Kiran must fix the critical login outage immediately.",
    172: "Lena will prepare the onboarding guide by next Thursday.",
    227: "Omar will book the venue for the team offsite before the end of May.",
}


def filler_sentence(rng: random.Random) -> str:

    topic, other = rng.sample(TOPICS, 2)

    period = rng.choice(PERIODS)

    template = rng.randrange(4)

    if template == 0:
        body = (
            f"looking at {topic}, the numbers from {period} "
            f"{rng.choice(TRENDS)}, {rng.choice(REACTIONS)}."
        )

    elif template == 1:
        body = (
            f"someone mentioned that {topic} "
            f"{rng.choice(FEELS)} compared to {period}."
        )

    elif template == 2:
        body = (
            f"honestly {topic} has been a talking point for a while, "
            f"and the feedback from {period} was mixed."
        )

    else:
        body = (
            f"on {topic}, there was a long discussion about how it "
            f"compares with {other}, and opinions differed."
        )

    text = rng.choice(OPENERS) + body

    return text[0].upper() + text[1:]


def build_meeting() -> dict:

    rng = random.Random(42)

    sentences = [
        PLANTED.get(index) or filler_sentence(rng)
        for index in range(TOTAL_SENTENCES)
    ]

    return {
        "name": "long",
        "description": (
            "About 4,500 words of neutral discussion with four tasks and one "
            "decision planted at the start and at the quarter points. Tests "
            "the context window and recall on long recordings. Generated by "
            "make_long_meeting.py."
        ),
        "transcript": " ".join(sentences),
        "gold": {
            "tasks": [
                {"kw": ["budget"], "owner": "Dana", "due": ["monday"], "priority": "MEDIUM"},
                {"kw": ["login|outage"], "owner": "Kiran", "due": [None, "immediately"], "priority": "HIGH"},
                {"kw": ["onboarding"], "owner": "Lena", "due": ["next thursday"], "priority": "MEDIUM"},
                {"kw": ["venue|offsite"], "owner": "Omar", "due": ["end of may"], "priority": "MEDIUM"},
            ],
            "optional": [],
            "decisions": [
                {"kw": ["hetzner"]},
            ],
        },
    }


if __name__ == "__main__":

    meeting = build_meeting()

    OUTPUT_FILE.parent.mkdir(exist_ok=True)

    OUTPUT_FILE.write_text(json.dumps(meeting, indent=2) + "\n")

    print(f"Wrote {OUTPUT_FILE} ({len(meeting['transcript'].split())} words)")
